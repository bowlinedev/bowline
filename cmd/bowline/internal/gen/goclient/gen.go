package goclient

import (
	"fmt"
	"go/format"
	"path"
	"sort"
	"strings"

	"github.com/bowlinedev/bowline/cmd/bowline/internal/gen/support"
	"github.com/bowlinedev/bowline/contract"
)

type Generator struct {
	Package string
}

func (g Generator) WithPackage(pkg string) any {
	g.Package = pkg
	return g
}

func (g Generator) Generate(doc *contract.Document, out string) ([]byte, error) {
	if err := support.Reject(doc, "go"); err != nil {
		return nil, err
	}
	pkg := g.Package
	if pkg == "" {
		pkg = path.Base(path.Dir(out))
		if pkg == "." || pkg == "/" || pkg == "" {
			pkg = "apiclient"
		}
	}
	pkg = packageIdentifier(pkg)
	gen := newGenerator(doc)
	declarations := gen.declarations()
	client := gen.client()
	var body strings.Builder
	body.WriteString(declarations)
	body.WriteString(client)
	body.WriteString(runtime)
	if gen.uses["iter"] {
		body.WriteString("\n" + streamRuntime)
	}
	if gen.uses["multipart"] {
		body.WriteString("\n" + uploadRuntime)
	}
	var b strings.Builder
	b.WriteString("// Code generated by bowline. DO NOT EDIT.\n\n")
	b.WriteString("package ")
	b.WriteString(pkg)
	b.WriteString("\n\n")
	b.WriteString(gen.imports())
	b.WriteString(body.String())
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("formatting generated client: %w\n%s", err, b.String())
	}
	return formatted, nil
}

func (g *generator) imports() string {
	std := []string{"bytes", "context", "encoding/json", "errors", "fmt", "io", "net/http", "net/url", "strings"}
	if g.uses["iter"] {
		std = append(std, "bufio", "iter")
	}
	if g.uses["multipart"] {
		std = append(std, "mime/multipart")
	}
	if g.uses["time"] {
		std = append(std, "time")
	}
	sort.Strings(std)
	var b strings.Builder
	b.WriteString("import (\n")
	for _, s := range std {
		b.WriteString("\t\"")
		b.WriteString(s)
		b.WriteString("\"\n")
	}
	b.WriteString("\n\t\"github.com/bowlinedev/bowline\"\n)\n\n")
	return b.String()
}
