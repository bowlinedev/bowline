package python

import (
	"sort"
	"strings"

	"github.com/bowlinedev/bowline/cmd/bowline/internal/gen/naming"
	"github.com/bowlinedev/bowline/cmd/bowline/internal/gen/support"
	"github.com/bowlinedev/bowline/contract"
)

type Generator struct{}

var keywords = map[string]bool{
	"False": true, "None": true, "True": true, "and": true, "as": true, "assert": true, "async": true,
	"await": true, "break": true, "class": true, "continue": true, "def": true, "del": true, "elif": true,
	"else": true, "except": true, "finally": true, "for": true, "from": true, "global": true, "if": true,
	"import": true, "in": true, "is": true, "lambda": true, "nonlocal": true, "not": true, "or": true,
	"pass": true, "raise": true, "return": true, "try": true, "while": true, "with": true, "yield": true,
	"match": true, "case": true, "type": true,
}

var moduleNames = []string{
	"Annotated", "AnyUrl", "AsyncIterator", "Base64Bytes", "BaseModel", "BigInt", "BinaryIO", "CallOptions",
	"Client", "ConfigDict", "DurationNs", "Empty", "Enum", "Field", "Generic", "IntEnum", "Iterator",
	"JsonValue", "Literal", "Method", "NewType", "SyncClient", "SyncTransport", "Transport", "TypeVar",
	"UUID", "annotations", "datetime",
}

type generator struct {
	doc      *contract.Document
	names    map[string]string
	uses     map[string]bool
	inline   map[string][]*contract.Field
	inlineOK []string
	params   map[string]bool
}

func newGenerator(doc *contract.Document) *generator {
	reserved := map[string]bool{}
	for k := range keywords {
		reserved[k] = true
	}
	for _, n := range moduleNames {
		reserved[n] = true
	}
	root := buildTree(doc.Procedures)
	var mounts []*node
	collectMounts(root, &mounts)
	for _, m := range mounts {
		reserved[m.className("")] = true
		reserved[m.className("Sync")] = true
	}
	params := map[string]bool{}
	for _, decl := range doc.Types {
		for _, p := range decl.Params {
			params[p] = true
			reserved[p] = true
		}
	}
	uses := map[string]bool{}
	if len(params) > 0 {
		uses["TypeVar"] = true
	}
	return &generator{doc: doc, names: naming.Assign(doc, reserved), uses: uses, inline: map[string][]*contract.Field{}, params: params}
}

func (g Generator) Generate(doc *contract.Document, out string) ([]byte, error) {
	if err := support.Reject(doc, "python"); err != nil {
		return nil, err
	}
	gen := newGenerator(doc)
	clients, err := gen.clients()
	if err != nil {
		return nil, err
	}
	declarations, err := gen.declarations()
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("# Code generated by bowline. DO NOT EDIT.\n\n")
	b.WriteString("from __future__ import annotations\n\n")
	b.WriteString(gen.imports())
	b.WriteString(gen.typeVars())
	b.WriteString(declarations)
	b.WriteString(clients)
	return []byte(strings.TrimRight(b.String(), "\n") + "\n"), nil
}

func (g *generator) imports() string {
	var b strings.Builder
	std := []struct {
		module string
		names  []string
	}{
		{"collections.abc", g.pick("AsyncIterator", "Iterator")},
		{"datetime", g.pick("datetime")},
		{"enum", g.pick("Enum", "IntEnum")},
		{"typing", g.pick("Annotated", "BinaryIO", "Generic", "Literal", "NewType", "TypeVar")},
		{"uuid", g.pick("UUID")},
	}
	wrote := false
	for _, imp := range std {
		if len(imp.names) == 0 {
			continue
		}
		b.WriteString("from " + imp.module + " import " + strings.Join(imp.names, ", ") + "\n")
		wrote = true
	}
	if wrote {
		b.WriteString("\n")
	}
	runtime := []string{"CallOptions", "Method", "SyncTransport", "Transport"}
	runtime = append(runtime, g.pick("BigInt", "DurationNs", "Empty")...)
	sort.Strings(runtime)
	b.WriteString("from bowline_client import " + strings.Join(runtime, ", ") + "\n")
	pyd := []string{"BaseModel", "ConfigDict"}
	pyd = append(pyd, g.pick("AnyUrl", "Base64Bytes", "Field", "JsonValue")...)
	sort.Strings(pyd)
	b.WriteString("from pydantic import " + strings.Join(pyd, ", ") + "\n\n\n")
	return b.String()
}

func (g *generator) pick(names ...string) []string {
	var out []string
	for _, n := range names {
		if g.uses[n] {
			out = append(out, n)
		}
	}
	return out
}

func (g *generator) typeVars() string {
	if len(g.params) == 0 {
		return ""
	}
	names := make([]string, 0, len(g.params))
	for p := range g.params {
		names = append(names, p)
	}
	sort.Strings(names)
	var b strings.Builder
	for _, p := range names {
		b.WriteString(p + " = TypeVar(\"" + p + "\")\n")
	}
	b.WriteString("\n\n")
	return b.String()
}

func identifier(s string) string {
	out := naming.Snake(s)
	if keywords[out] {
		out += "_"
	}
	return out
}

func memberName(s string) string {
	out := naming.Identifier(s)
	out = strings.ReplaceAll(out, "$", "_")
	if out == "" {
		return "X"
	}
	if out[0] >= 'a' && out[0] <= 'z' {
		out = strings.ToUpper(out[:1]) + out[1:]
	}
	if keywords[out] {
		out += "_"
	}
	return out
}

func docstring(b *strings.Builder, indent, doc, deprecated string) {
	doc = strings.TrimSpace(doc)
	if deprecated != "" {
		if doc != "" {
			doc += "\n\n"
		}
		doc += "Deprecated: " + strings.TrimSpace(deprecated)
	}
	if doc == "" {
		return
	}
	doc = strings.ReplaceAll(doc, `"""`, `\"\"\"`)
	lines := strings.Split(doc, "\n")
	if len(lines) == 1 {
		b.WriteString(indent + `"""` + lines[0] + `"""` + "\n")
		return
	}
	b.WriteString(indent + `"""` + strings.TrimSpace(lines[0]) + "\n")
	for _, line := range lines[1:] {
		line = strings.TrimSpace(line)
		if line == "" {
			b.WriteString("\n")
			continue
		}
		b.WriteString(indent + line + "\n")
	}
	b.WriteString(indent + `"""` + "\n")
}
