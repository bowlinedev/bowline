package elixir

import (
	"cmp"
	"path"
	"slices"
	"strings"

	"github.com/bowlinedev/bowline/cmd/bowline/internal/gen/naming"
	"github.com/bowlinedev/bowline/cmd/bowline/internal/gen/support"
	"github.com/bowlinedev/bowline/contract"
)

const lineWidth = 98

type Generator struct {
	Package string
}

func (g Generator) WithPackage(pkg string) any {
	g.Package = pkg
	return g
}

func (g Generator) Generate(doc *contract.Document, out string) ([]byte, error) {
	if err := support.Reject(doc, "elixir"); err != nil {
		return nil, err
	}
	root := g.Package
	if root == "" {
		root = strings.TrimSuffix(path.Base(out), path.Ext(out))
	}
	root = rootModule(root)
	gen := newGenerator(doc, root)
	var b strings.Builder
	b.WriteString("# Code generated by bowline. DO NOT EDIT.\n\n")
	gen.writeNominals(&b)
	for _, id := range gen.order {
		gen.writeDecl(&b, id, gen.doc.Types[id])
	}
	for _, id := range gen.errorOrder {
		decl := gen.doc.Errors[id]
		gen.writeStruct(&b, gen.types+"."+gen.names[id], gen.names[id], docOr(decl.Doc, decl.Name+" is the details shape of the "+decl.Name+" error variant ("+decl.Code+")."), decl.Fields, nil, "")
	}
	gen.writeClients(&b)
	return []byte(strings.TrimRight(b.String(), "\n") + "\n"), nil
}

type generator struct {
	helpers    helperPool
	doc        *contract.Document
	root       string
	types      string
	names      map[string]string
	order      []string
	errorOrder []string
	nominals   []string
}

func newGenerator(doc *contract.Document, root string) *generator {
	g := &generator{doc: doc, root: root, types: root + ".Types", names: assignNames(doc)}
	for id, decl := range doc.Types {
		if decl.Kind == contract.Primitive {
			g.nominals = append(g.nominals, id)
			continue
		}
		g.order = append(g.order, id)
	}
	slices.SortFunc(g.order, func(a, b string) int { return cmp.Compare(g.names[a], g.names[b]) })
	slices.SortFunc(g.nominals, func(a, b string) int { return cmp.Compare(g.names[a], g.names[b]) })
	for id := range doc.Errors {
		g.errorOrder = append(g.errorOrder, id)
	}
	slices.SortFunc(g.errorOrder, func(a, b string) int { return cmp.Compare(g.names[a], g.names[b]) })
	return g
}

func rootModule(name string) string {
	parts := strings.Split(name, ".")
	for i, p := range parts {
		parts[i] = naming.UpperCamel(p)
	}
	return strings.Join(parts, ".")
}

func docOr(doc, fallback string) string {
	if strings.TrimSpace(doc) != "" {
		return doc
	}
	return fallback
}

func writeModuleDoc(b *strings.Builder, indent, attr, doc string) {
	doc = strings.TrimSpace(doc)
	if doc == "" {
		if attr == "@moduledoc" {
			b.WriteString(indent)
			b.WriteString("@moduledoc false\n")
		}
		return
	}
	b.WriteString(indent)
	b.WriteString(attr)
	b.WriteString(" \"\"\"\n")
	for line := range strings.SplitSeq(doc, "\n") {
		if strings.TrimSpace(line) == "" {
			b.WriteString("\n")
			continue
		}
		b.WriteString(indent)
		b.WriteString(escapeDoc(line))
		b.WriteString("\n")
	}
	b.WriteString(indent)
	b.WriteString("\"\"\"\n")
}

func escapeDoc(line string) string {
	line = strings.ReplaceAll(line, `\`, `\\`)
	line = strings.ReplaceAll(line, `"""`, `\"\"\"`)
	return strings.ReplaceAll(line, "#{", `\#{`)
}

func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '#':
			b.WriteString(`\#`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
