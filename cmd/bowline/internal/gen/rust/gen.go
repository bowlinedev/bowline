package rust

import (
	"sort"
	"strings"

	"github.com/bowlinedev/bowline/cmd/bowline/internal/gen/naming"
	"github.com/bowlinedev/bowline/contract"
)

type Generator struct{}

func (Generator) Generate(doc *contract.Document, out string) ([]byte, error) {
	g := newGenerator(doc)
	declarations := g.declarations()
	client := g.client()
	var b strings.Builder
	b.WriteString("// Code generated by bowline. DO NOT EDIT.\n\n")
	b.WriteString(g.imports())
	b.WriteString(declarations)
	b.WriteString(client)
	return []byte(b.String()), nil
}

type generator struct {
	doc        *contract.Document
	names      map[string]string
	order      []string
	errorOrder []string
	synthetic  []string
	synthBody  map[string]string
	uses       map[string]bool
}

func newGenerator(doc *contract.Document) *generator {
	g := &generator{doc: doc, names: assignNames(doc), uses: map[string]bool{}, synthBody: map[string]string{}}
	for id := range doc.Types {
		g.order = append(g.order, id)
	}
	sort.Slice(g.order, func(i, j int) bool { return g.names[g.order[i]] < g.names[g.order[j]] })
	for id := range doc.Errors {
		g.errorOrder = append(g.errorOrder, id)
	}
	sort.Slice(g.errorOrder, func(i, j int) bool { return g.names[g.errorOrder[i]] < g.names[g.errorOrder[j]] })
	return g
}

var reservedTypeNames = map[string]bool{
	"Client": true, "Transport": true, "Error": true, "Issue": true, "CallOptions": true, "Method": true,
	"Validate": true, "Empty": true, "Option": true, "Vec": true, "Box": true, "String": true, "Result": true,
	"Some": true, "None": true, "Ok": true, "Err": true, "Self": true, "Stream": true, "Body": true,
}

var keywords = map[string]bool{
	"as": true, "async": true, "await": true, "break": true, "const": true, "continue": true, "crate": true,
	"dyn": true, "else": true, "enum": true, "extern": true, "false": true, "fn": true, "for": true, "if": true,
	"impl": true, "in": true, "let": true, "loop": true, "match": true, "mod": true, "move": true, "mut": true,
	"pub": true, "ref": true, "return": true, "self": true, "static": true, "struct": true, "super": true,
	"trait": true, "true": true, "type": true, "unsafe": true, "use": true, "where": true, "while": true,
	"abstract": true, "become": true, "box": true, "do": true, "final": true, "macro": true, "override": true,
	"priv": true, "try": true, "typeof": true, "unsized": true, "virtual": true, "yield": true, "gen": true,
}

var rawForbidden = map[string]bool{"self": true, "Self": true, "super": true, "crate": true}

func assignNames(doc *contract.Document) map[string]string {
	base := naming.Assign(doc, nil)
	ids := make([]string, 0, len(base))
	for id := range base {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	names := map[string]string{}
	used := map[string]bool{}
	for _, id := range ids {
		name := typeName(base[id])
		if reservedTypeNames[name] {
			name += "Type"
		}
		for used[name] {
			name += "_"
		}
		used[name] = true
		names[id] = name
	}
	return names
}

func typeName(s string) string {
	name := naming.UpperCamel(strings.ReplaceAll(s, "$", "_"))
	if name == "" {
		return "X"
	}
	return name
}

func fieldName(json string) string {
	name := naming.Snake(json)
	if keywords[name] {
		if rawForbidden[name] {
			return name + "_"
		}
		return "r#" + name
	}
	return name
}

func methodName(segment string) string {
	return fieldName(segment)
}

func (g *generator) imports() string {
	var items []string
	for _, item := range []string{"Body", "CallOptions", "Empty", "Error", "Issue", "Method", "Stream", "Transport", "Validate", "rules"} {
		if g.uses[item] {
			items = append(items, item)
		}
	}
	var b strings.Builder
	if len(items) > 0 {
		b.WriteString("use bowline_client::{" + strings.Join(items, ", ") + "};\n")
	}
	if g.uses["serde"] {
		b.WriteString("use serde::{Deserialize, Serialize};\n")
	}
	if b.Len() > 0 {
		b.WriteString("\n")
	}
	return b.String()
}

func writeDoc(b *strings.Builder, indent, doc string) {
	doc = strings.TrimSpace(doc)
	if doc == "" {
		return
	}
	for _, line := range strings.Split(doc, "\n") {
		b.WriteString(indent + "/// " + strings.TrimSpace(line) + "\n")
	}
}
