type generator struct {
	doc       *contract.Document
	names     map[string]string
	usedNames map[string]bool
	order     []string
	inline    map[*contract.Type]*inlineDecl
	inlines   []*inlineDecl
	uses      map[string]bool
}

type inlineDecl struct {
	name   string
	fields []*contract.Field
	params []string
}

func (Generator) Generate(doc *contract.Document, out string) ([]byte, error) {
	if err := support.Reject(doc, "dart"); err != nil {
		return nil, err
	}
	g := newGenerator(doc)
	if err := g.collectInlines(); err != nil {
		return nil, err
	}
	var body strings.Builder
	if err := g.declarations(&body); err != nil {
		return nil, err
	}
	if err := g.clients(&body); err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("// Generated by bowline. DO NOT EDIT.\n\n")
	if g.uses["typed_data"] {
		b.WriteString("import 'dart:typed_data';\n\n")
	}
	b.WriteString("import 'package:bowline/bowline.dart';\n\n")
	b.WriteString(body.String())
	return []byte(strings.TrimRight(b.String(), "\n") + "\n"), nil
}

func newGenerator(doc *contract.Document) *generator {
	base := naming.Assign(doc, nil)
	g := &generator{doc: doc, names: map[string]string{}, usedNames: map[string]bool{}, inline: map[*contract.Type]*inlineDecl{}, uses: map[string]bool{}}
	ids := make([]string, 0, len(base))
	for id := range base {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		g.names[id] = g.uniqueType(naming.UpperCamel(base[id]))
	}
	for id := range doc.Types {
		g.order = append(g.order, id)
	}
	sort.Slice(g.order, func(i, j int) bool { return g.names[g.order[i]] < g.names[g.order[j]] })
	return g
}

func (g *generator) uniqueType(name string) string {
	if name == "" {
		name = "Type_"
	}
	candidate := name
	if reservedTypes[candidate] || reserved[candidate] || builtins[candidate] {
		candidate += "_"
	}
	for n := 2; g.usedNames[candidate]; n++ {
		candidate = fmt.Sprintf("%s%d", name, n)
	}
	g.usedNames[candidate] = true
	return candidate
}

func fieldName(json string) string {
	name := naming.LowerCamel(json)
	if reserved[name] || reservedMembers[name] {
		name += "_"
	}
	return name
}

func memberNames(fields []*contract.Field) map[string]string {
	out := map[string]string{}
	used := map[string]bool{}
	for _, f := range fields {
		name := fieldName(f.Name)
		for used[name] {
			name += "_"
		}
		used[name] = true
		out[f.Name] = name
	}
	return out
}

func (g *generator) collectInlines() error {
	for _, id := range g.order {
		decl := g.doc.Types[id]
		switch decl.Kind {
		case contract.Struct:
			g.walkFields(decl.Fields, g.names[id], nil)
		case contract.Generic:
			if decl.Body != nil {
				g.walkFields(decl.Body.Fields, g.names[id], decl.Params)
			}
		}
	}
	errIDs := g.errorOrder()
	for _, id := range errIDs {
		g.walkFields(g.doc.Errors[id].Fields, g.names[id], nil)
	}
	procs := append([]*contract.Procedure(nil), g.doc.Procedures...)
	sort.Slice(procs, func(i, j int) bool { return procs[i].Path < procs[j].Path })
	for _, p := range procs {
		base := procTypeName(p.Path)
		g.walkNode(p.Input, base+"Input", nil)
		g.walkNode(p.Output, base+"Output", nil)
	}
	return nil
}

func procTypeName(path string) string {
	var b strings.Builder
	for s := range strings.SplitSeq(path, ".") {
		b.WriteString(naming.UpperCamel(s))
	}
	return b.String()
}

func (g *generator) walkFields(fields []*contract.Field, owner string, params []string) {
	for _, f := range fields {
		g.walkNode(f.Type, owner+naming.UpperCamel(f.Name), params)
	}
}

func (g *generator) walkNode(t *contract.Type, name string, params []string) {
	if t == nil {
		return
	}
	switch t.Kind {
	case contract.Struct:
		if len(t.Fields) == 0 {
			return
		}
		if _, done := g.inline[t]; done {
			return
		}
		decl := &inlineDecl{name: g.uniqueType(name), fields: t.Fields, params: usedParams(t, params)}
		g.inline[t] = decl
		g.inlines = append(g.inlines, decl)
		g.walkFields(t.Fields, decl.name, params)
	case contract.Array:
		g.walkNode(t.Elem, name+"Item", params)
	case contract.Map:
		g.walkNode(t.Value, name+"Value", params)
	case contract.Ref:
		for i, a := range t.Args {
			g.walkNode(a, fmt.Sprintf("%sArg%d", name, i), params)
		}
	}
}

func usedParams(t *contract.Type, params []string) []string {
	if len(params) == 0 {
		return nil
	}
	found := map[string]bool{}
	var visit func(n *contract.Type)
	visit = func(n *contract.Type) {
		if n == nil {
			return
		}
		if n.Kind == contract.Param {
			found[n.Name] = true
		}
		for _, f := range n.Fields {
			visit(f.Type)
		}
		visit(n.Elem)
		visit(n.Key)
		visit(n.Value)
		for _, a := range n.Args {
			visit(a)
		}
	}
	visit(t)
	var out []string
	for _, p := range params {
		if found[p] {
			out = append(out, p)
		}
	}
	return out
}

func (g *generator) errorOrder() []string {
	ids := make([]string, 0, len(g.doc.Errors))
	for id := range g.doc.Errors {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool { return g.names[ids[i]] < g.names[ids[j]] })
	return ids
}

func writeDoc(b *strings.Builder, indent, doc string) {
	doc = strings.TrimSpace(doc)
	if doc == "" {
		return
	}
	for line := range strings.SplitSeq(doc, "\n") {
		b.WriteString(indent)
		b.WriteString("/// ")
		b.WriteString(strings.TrimSpace(line))
		b.WriteString("\n")
	}
}

func quote(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `'`, `\'`)
	s = strings.ReplaceAll(s, `$`, `\$`)
	return "'" + s + "'"
}
